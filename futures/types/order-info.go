/*
FILE: futures/types/order-info.go

DESCRIPTION:
Order state for the KuCoin Futures profile, mapped from
GET /api/v1/orders/{orderId}, GET /api/v1/orders (list) and the private WS
"/contractMarket/tradeOrders" channel.

KuCoin reports terminal orders with Status == "done" and IsActive == false;
the filled vs. cancelled distinction is read from FilledSize / CancelExist.
The private WS channel additionally carries per-push event fields
(EventType, TradeID, MatchSize/MatchPrice, Liquidity, TsNs) that let a
consumer treat every "match" push as one exact execution.
Sizes are in CONTRACTS; values are in the settle currency.
*/

package types

import "github.com/shopspring/decimal"

// OrderInfo — KuCoin Futures order state.
type OrderInfo struct {
	OrderID       string
	ClientOrderID string
	Symbol        string
	Type          OrderType
	Side          SideType

	Price decimal.Decimal
	Size  decimal.Decimal
	Value decimal.Decimal

	// FilledSize / FilledValue — cumulative fills (dealSize / dealValue).
	FilledSize  decimal.Decimal
	FilledValue decimal.Decimal

	Leverage    decimal.Decimal
	TimeInForce TimeInForceType
	MarginMode  MarginMode

	PostOnly    bool
	Hidden      bool
	Iceberg     bool
	VisibleSize decimal.Decimal
	ReduceOnly  bool
	CloseOrder  bool
	ForceHold   bool

	// Stop / conditional fields.
	Stop          StopType
	StopPriceType StopPriceType
	StopPrice     decimal.Decimal
	StopTriggered bool

	// Status — "open"/"done"; IsActive/CancelExist disambiguate.
	Status      OrderStatus
	IsActive    bool
	CancelExist bool

	Remark         string
	SettleCurrency string

	CreatedAtMs int64
	UpdatedAtMs int64

	// ---- Private WS push only ("/contractMarket/tradeOrders") --------------
	// Zero on REST. Additive (v2.8): lets a consumer build an exact fill
	// ledger from lifecycle events instead of diffing the FilledSize cumulative.

	// EventType — lifecycle event of the push (`type`): "open" (resting in
	// the book), "match" (one execution), "filled" (fully executed,
	// terminal), "canceled" (terminal), "update" (size decreased). Status is
	// the resulting order state ("open"/"match"/"done").
	EventType string
	// TradeID — execution id generated by the matching engine (`tradeId`);
	// set on "match" pushes only.
	TradeID string
	// MatchSize / MatchPrice — size (CONTRACTS) and price of THIS execution
	// (`matchSize` / `matchPrice`); set on "match" pushes only. FilledSize
	// stays the cumulative filled size after the execution.
	MatchSize  decimal.Decimal
	MatchPrice decimal.Decimal
	// Liquidity — maker/taker role of this execution (`liquidity`); set on
	// "match" pushes only.
	Liquidity Liquidity
	// TsNs — matching-engine timestamp of the push in NANOSECONDS (`ts`),
	// unrounded; UpdatedAtMs is the same instant truncated to milliseconds.
	TsNs int64
}
