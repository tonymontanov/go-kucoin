/*
FILE: spot/types/order-info.go

DESCRIPTION:
Order state for the KuCoin Spot profile, mapped from
GET /api/v1/orders/{orderId}, GET /api/v1/orders (list) and the private WS
"/spotMarket/tradeOrders" channel.

KuCoin Spot REST reports an order as active via IsActive (true = open /
partially filled, false = terminal); CancelExist distinguishes a cancel from
a full fill. The private WS channel additionally carries a lifecycle Status
("open"/"match"/"done") which is surfaced verbatim, plus per-push event
fields (EventType, TradeID, MatchSize/MatchPrice, Liquidity, TsNs) that let
a consumer treat every "match" push as one exact execution. Sizes are in
BASE currency; funds are in QUOTE currency.
*/

package types

import "github.com/shopspring/decimal"

// OrderInfo — KuCoin Spot order state.
type OrderInfo struct {
	OrderID       string
	ClientOrderID string
	Symbol        string
	Type          OrderType
	Side          SideType

	Price decimal.Decimal
	// Size — order size (base currency).
	Size decimal.Decimal
	// Funds — order value (quote currency); set for market-by-funds orders.
	Funds decimal.Decimal

	// DealSize / DealFunds — cumulative filled size (base) / value (quote).
	DealSize  decimal.Decimal
	DealFunds decimal.Decimal

	TimeInForce TimeInForceType
	TradeType   TradeType

	PostOnly    bool
	Hidden      bool
	Iceberg     bool
	VisibleSize decimal.Decimal
	CancelAfter int64

	STP SelfTradePrevention

	// Fee / FeeCurrency — cumulative fee paid.
	Fee         decimal.Decimal
	FeeCurrency string

	// Status — lifecycle subject on the private WS ("open"/"match"/"done");
	// empty on REST, where IsActive / CancelExist are authoritative.
	Status      OrderStatus
	IsActive    bool
	CancelExist bool

	Remark      string
	CreatedAtMs int64
	UpdatedAtMs int64

	// ---- Private WS push only ("/spotMarket/tradeOrders") ------------------
	// Zero on REST. Additive (v2.8): lets a consumer build an exact fill
	// ledger from lifecycle events instead of diffing the DealSize cumulative.

	// EventType — lifecycle event of the push (`type`): "received" (entered
	// the matching engine), "open" (resting in the book), "match" (one
	// execution), "filled" (fully executed, terminal), "canceled"
	// (terminal), "update" (size decreased). Status is the resulting order
	// state ("open"/"match"/"done").
	EventType string
	// TradeID — execution id generated by the matching engine (`tradeId`);
	// set on "match" pushes only.
	TradeID string
	// MatchSize / MatchPrice — size (base) and price of THIS execution
	// (`matchSize` / `matchPrice`); set on "match" pushes only. DealSize
	// stays the cumulative filled size after the execution.
	MatchSize  decimal.Decimal
	MatchPrice decimal.Decimal
	// Liquidity — maker/taker role of this execution (`liquidity`); set on
	// "match" pushes only.
	Liquidity Liquidity
	// TsNs — matching-engine timestamp of the push in NANOSECONDS (`ts`),
	// unrounded; UpdatedAtMs is the same instant truncated to milliseconds.
	TsNs int64
}
